'use client';

import type { Attempt, Question } from '@/types';

/**
 * Номера всех вопросов теста: где ответил, где нет, где находишься сейчас.
 *
 * ЧТО ТУТ БЫЛО РАНЬШЕ. Полоса прогресса — одна охряная линия, которая росла
 * к концу теста. Она отвечала ровно на один вопрос, «сколько осталось», и не
 * отвечала на более важный: какие вопросы остались пустыми. Пропустить
 * вопрос было можно (и нужно — см. принцип 13), а узнать об этом — только на
 * экране результатов, когда счёт уже посчитан и занижен.
 *
 * Недолго вместо этого жил отдельный экран сверки перед результатами. Он
 * был не нужен: он сообщал о пропусках в конце, когда человек уже устал и
 * хочет увидеть цифру, — а сообщать надо сразу. Пропустил четвёртый, видишь
 * это на седьмом, чинишь тогда же. Здесь же решается и то, ради чего экран
 * сверки вообще появился: вернуться к пропущенному вопросу раньше было
 * физически нечем, навигация была только «назад/вперёд».
 *
 * ПОЧЕМУ НОМЕРА, А НЕ ТОЧКИ. Точки заняли бы один ряд вместо двух, но по
 * точке нельзя попасть пальцем и нельзя сказать «вернись к девятому».
 * Прогресс номера показывают не хуже: видно, где ты в ряду.
 *
 * ЦВЕТ НЕ ЕДИНСТВЕННЫЙ ПРИЗНАК. Отвечённый — залитый тёмным с светлой
 * цифрой, пустой — контурный с тёмной: различаются инверсией, а не оттенком,
 * поэтому видны и при дальтонизме, и на выцветшем экране на солнце.
 * Контрасты посчитаны: цифра на заливке 15,55 в светлой теме и 14,19 в
 * тёмной, цифра пустого — 7,42 и 9,17, охряное кольцо текущего на фоне
 * страницы — 3,94 и 8,19 при норме 3 для графики.
 */
export default function QuestionNav({
  questions,
  answers,
  index,
  onJump,
}: {
  questions: Question[];
  answers: Attempt['answers'];
  /** Текущий вопрос, от нуля. */
  index: number;
  onJump: (next: number) => void;
}) {
  return (
    <ul className="flex flex-wrap gap-2.5">
      {questions.map((q, i) => {
        const answered = Boolean(answers[q.id]?.choiceId);
        const current = i === index;
        return (
          <li key={q.id}>
            <button
              type="button"
              onClick={() => onJump(i)}
              aria-current={current ? 'true' : undefined}
              /* Состояние сказано словами: значок цвета скринридер не видит,
                 а «отвечён» — это ровно то, что здесь нужно знать. */
              aria-label={`Question ${i + 1}, ${answered ? 'answered' : 'not answered'}`}
              className={`flex h-8 w-8 items-center justify-center rounded font-mono text-[11px] tabular-nums transition-colors ${
                answered
                  ? 'bg-ink text-ground hover:opacity-85'
                  : 'border border-rule-strong text-ink-soft hover:bg-surface'
              } ${
                /* Кольцо с отступом: по обе стороны от него фон страницы, а
                   не заливка чипа. Иначе в тёмной теме охра легла бы на
                   светлую заливку с контрастом 1,73 и пропала. */
                current ? 'ring-2 ring-ochre ring-offset-2 ring-offset-ground' : ''
              }`}
            >
              {i + 1}
            </button>
          </li>
        );
      })}
    </ul>
  );
}
