import qrcode from 'qrcode-generator';

/**
 * QR-код ссылки на чат WhatsApp — для тех, кто открыл сайт на компьютере.
 *
 * ЗАЧЕМ. Родители часто читают сайт с рабочего компьютера, а WhatsApp у них
 * в телефоне. Кнопка на компьютере открывает страницу wa.me, которая просит
 * установить WhatsApp Desktop или войти в WhatsApp Web по QR-коду, — лишний
 * круг, на котором человек теряется. Этот код камера телефона открывает сразу
 * в чате, с тем же заготовленным сообщением, что у кнопки. На телефоне код не
 * показывается: там кнопка и так открывает приложение.
 *
 * КАК. Код считается при сборке, на сервере, и уходит в браузер готовым SVG:
 * ни библиотеки, ни скрипта на стороне посетителя. Каждый тёмный модуль —
 * квадрат 1×1 в одном пути, поэтому код остаётся резким на любом экране.
 *
 * ЦВЕТА НЕ ЗАВИСЯТ ОТ ТЕМЫ. Тёмные модули на белом всегда, в том числе в
 * тёмной теме: инвертированный код (светлое на тёмном) часть камер и
 * сканеров не распознаёт. Белое поле вокруг — обязательная по стандарту
 * «тихая зона» шириной в 4 модуля, без неё код читается хуже.
 */
export default function WhatsAppQr({ href, label }: { href: string; label: string }) {
  // M — средний уровень коррекции ошибок: код переживает блик на экране и
  // неровную съёмку, но остаётся не слишком плотным для длинной ссылки.
  const qr = qrcode(0, 'M');
  qr.addData(href);
  qr.make();

  const count = qr.getModuleCount();
  const quiet = 4;
  const size = count + quiet * 2;
  let d = '';
  for (let row = 0; row < count; row++) {
    for (let col = 0; col < count; col++) {
      if (qr.isDark(row, col)) d += `M${col + quiet} ${row + quiet}h1v1h-1z`;
    }
  }

  return (
    <svg
      viewBox={`0 0 ${size} ${size}`}
      role="img"
      aria-label={label}
      shapeRendering="crispEdges"
      className="h-auto w-full"
    >
      <rect width={size} height={size} fill="#ffffff" />
      <path d={d} fill="#12203a" />
    </svg>
  );
}
